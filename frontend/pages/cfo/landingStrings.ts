// Landing-page copy, per language.
//
// The landing renders from static HTML template strings (see Landing.tsx), so
// it can't use react-i18next keys inline the way app surfaces do. Instead the
// templates are functions of one typed strings object, and the language
// picker in the landing header swaps which dictionary is passed in.
//
// Scope note: the three LEGAL DOCUMENTS (privacy / cookies / terms) are
// deliberately NOT translated — legal text needs a lawyer, not a model. They
// render in English with a translated notice (legal.englishNote).
//
// Tokens: FAQ answers may contain {privacy} / {terms}; the consent body may
// contain {cookiePolicy}. Landing.tsx replaces them with localized in-page
// link buttons.
//
// NO ACCURACY OR COVERAGE NUMBER IS TYPED IN THIS FILE (owner, 2026-10-01).
// The first public review found "eight calibration fixtures" in one sentence
// and "9 / 9" in the block beside it — both typed by hand, counting different
// things, neither dated. Every such number now arrives through a dotted
// token — {rerun.books}, {balance.exact}, {turnover.tol}, {bvb.listings},
// {coverage.ai_read.availability} … — filled from frontend/data/
// engineProof.json (generated by scripts/build_engine_proof.py, which RUNS
// the checks) and frontend/data/coverage.json. `LANDING_STRINGS` is the raw
// copy, tokens and all; `landingStringsFor()` returns it filled for a
// language. Gates `landing-proof` and `public-claims` red on a typed number
// and on a coverage claim that is not a row of coverage.json.

import type { FeatureKey } from "@/lib/features";
import { fillProofDeep, type ProofCheckId } from "@/lib/engineProof";

export interface LandingStrings {
  nav: { home: string; pricing: string; legal: string; contact: string; workspace: string; language: string };
  auth: { signIn: string; getStartedFree: string };
  menu: { openApp: string; settings: string; signOut: string };
  signout: { title: string; body: string; cancel: string; confirm: string };
  hero: {
    eyebrow: string;
    t1: string; thl: string; t2: string;
    body: string;
    ctaStart: string; ctaSignIn: string;
    checks: string[];
    mockNote: string;
    /** Title line of the fake browser chrome on the hero mock. */
    mockTitle: string;
    /** The illustrative dashboard under the hero, in the reader's language
     *  and number format. Invented figures, labelled illustrative by
     *  `mockNote`; none is a claim about the engine. */
    mock: {
      kpis: { label: string; value: string; unit: string; sub: string }[];
      briefingTitle: string;
      briefingBody: string;
      bullets: string[];
    };
  };
  stats: { drift: string; ratios: string; peers: string; upload: string };
  modules: {
    eyebrow: string; t1: string; thl: string;
    /** `featureKey` is the `_features.py` row the card sells. It is not
     *  decoration: `shippedClaimsMatchCode.test.ts` parses the real
     *  registry and reds when a card names a row that is not `active`.
     *  A fourth card ("Invoice Intelligence") was removed on 2026-09-08
     *  for exactly that reason — `invoices` is `hidden`, and its own
     *  PendingState says it waits on e-Factura ingestion nobody has
     *  built, while this card described it in the present tense as
     *  "surfaced as dedicated tabs inside your statements". */
    cards: { kicker: string; title: string; body: string; featureKey: FeatureKey }[];
  };
  how: {
    eyebrow: string; t1: string; thl: string;
    steps: { title: string; body: string }[];
  };
  /** The words around the coverage table beside the upload step. The table
   *  itself — every row, count and date — is frontend/data/coverage.json,
   *  rendered through lib/coverage. */
  coverage: { eyebrow: string; evidenceLabel: string; asOfLabel: string };
  /** The public sample: a FICTIONAL Romanian company's trial balance and
   *  the complete report generated from it (route /sample). */
  sample: { kicker: string; title: string; body: string; cta: string; proofCta: string };
  defensible: {
    eyebrow: string; title: string; body: string;
    bullets: { strong: string; rest: string }[];
    /** Engine proof block. The headline value of each row ("6 / 7"), what
     *  is checked and the date are read from engineProof.json; `captions`
     *  is the result in words, by check id, tokens only. `measured` carries
     *  `{when}`, which the page replaces with the row's own date. */
    proof: {
      label: string;
      captions: Record<ProofCheckId, string>;
      measured: string;
      note: string;
    };
  };
  audiences: {
    eyebrow: string; t1: string; thl: string;
    cards: { title: string; body: string }[];
  };
  faq: { eyebrow: string; title: string; items: { q: string; a: string }[] };
  cta: { t1: string; thl: string; body: string; start: string; signIn: string; goWorkspace: string };
  pricing: {
    eyebrow: string; t1: string; thl: string; subtitle: string; note: string; perMonth: string;
    solo: { name: string; yearly: string; blurb: string; cta: string; features: string[] };
    business: { badge: string; name: string; yearly: string; blurb: string; cta: string; lead: string[]; features: string[] };
    /** Multi-Country — COMING SOON. International coverage is not available
     *  (coverage.json row `other_countries`), so the card stays visible, is
     *  marked `badge`, and its `cta` is a disabled label, not a checkout link. */
    pro: { name: string; badge: string; price: string; priceNote: string; blurb: string; cta: string; lead: string[]; features: string[] };
  };
  legal: {
    eyebrow: string; title: string; subtitle: string; englishNote: string;
    privacy: string; cookies: string; terms: string;
  };
  contact: {
    eyebrow: string; title: string; subtitle: string;
    phName: string; phEmail: string; phCompany: string; phMessage: string;
    invalid: string; error: string; sending: string; send: string;
    sentTitle: string; sentBody: string; note: string;
    sales: { kicker: string; blurb: string };
    support: { kicker: string; blurb: string };
    privacy: { kicker: string; blurb: string };
    office: string;
  };
  footer: {
    blurb: string;
    product: string; overview: string; how: string; trust: string; audiences: string; faq: string;
    legalCol: string; cookieSettings: string;
    contactCol: string; contactUs: string;
    rights: string; madeIn: string;
  };
  consent: {
    title: string; body: string;
    necessary: string; necessaryDesc: string; alwaysOn: string;
    analytics: string; analyticsDesc: string;
    marketing: string; marketingDesc: string;
    acceptAll: string; rejectAll: string; save: string; customise: string;
  };
}

