/** The RAW copy — proof and coverage tokens unfilled. The gates read this
 *  to prove no accuracy number is typed; nothing renders it directly. */
export const LANDING_STRINGS: Record<string, LandingStrings> = { en, ro };

const FILLED: Record<string, LandingStrings> = {};

/** The copy for a language, every `{proof…}` / `{coverage…}` token filled
 *  from engineProof.json and coverage.json in that language's number and
 *  date format. An unknown token throws (lib/engineProof.fillProof). */
export function landingStringsFor(langCode: string): LandingStrings {
  const code = LANDING_STRINGS[langCode] ? langCode : "en";
  return (FILLED[code] ??= fillProofDeep(LANDING_STRINGS[code], code));
}
