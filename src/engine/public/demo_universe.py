"""Demo universe snapshots — 54 entries with indicative FY2024 values
sourced from public 10-K / annual filings.

Every snapshot is tagged ``source="demo"`` so the FE renders the Demo
badge unmistakably. Numbers are illustrative (rounded to the nearest
hundred million for revenue, nearest billion for market cap) — they're
not meant to be tick-accurate. The point is the table reads as credible
when the operator first opens it and the API key isn't yet entitled.

Currency = USD throughout. Margins / multiples are ratios where the
unit is "1" (P/E 28.5 means 28.5×), pct fields are stored as the
percentage value (28.5 means 28.5%).

When a metric isn't known with confidence, the field is `None`. The
FE renders `None` as `—` per the Money primitive's missing-data
convention — never as `0`.
"""

from __future__ import annotations
from typing import Any, Dict, Optional

# ── Shape contract ──────────────────────────────────────────────────────
# Matches PublicCompanyFinancialSnapshot in the FE (lib/publicCompanyUniverseTypes.ts).
# When you add a field here, mirror it there.

# The as-of date the demo table declares for itself. It is also the row's
# ``lastUpdated``: the demo values are a static table, and the only date
# that is TRUE of them is the one this module declares. Until 2026-09-04
# ``lastUpdated`` was ``datetime.now()`` at import — the process clock at
# engine boot — and every demo card read "computed <container start>".
_LAST_UPDATED = "2025-12-31"  # As-of date stamped on every demo row.


def _row(
    *, ticker: str, name: str, sector: str,
    market_cap_b: Optional[float] = None,
    revenue_b: Optional[float] = None,
    revenue_growth_pct: Optional[float] = None,
    gross_margin_pct: Optional[float] = None,
    ebitda_margin_pct: Optional[float] = None,
    net_margin_pct: Optional[float] = None,
    operating_cash_flow_b: Optional[float] = None,
    capex_b: Optional[float] = None,
    cash_b: Optional[float] = None,
    gross_debt_b: Optional[float] = None,
    net_debt_b: Optional[float] = None,
    equity_b: Optional[float] = None,
    pe: Optional[float] = None,
    ev_ebitda: Optional[float] = None,
    ev_sales: Optional[float] = None,
    fcf_yield_pct: Optional[float] = None,
    dividend_yield_pct: Optional[float] = None,
    roe_pct: Optional[float] = None,
    roa_pct: Optional[float] = None,
    nd_to_ebitda: Optional[float] = None,
    debt_to_equity: Optional[float] = None,
) -> Dict[str, Any]:
    """Build a single demo snapshot row. All money inputs are in BILLIONS
    of USD; we multiply up to raw USD here so the FE Money component
    can apply FX conversion uniformly.

    PUB-200 — also derives a plausible per-share `price` from the market
    cap so the universe table can render a Price column without fetching
    SEP for 200 tickers up-front. Same heuristic the price-history synth
    uses for its anchor, so the table's Price matches the drawer chart's
    last point for demo rows.
    """
    def _b(x: Optional[float]) -> Optional[float]:
        return x * 1_000_000_000 if x is not None else None

    def _synth_price(mc: Optional[float]) -> Optional[float]:
        """USD-per-share derived from market cap. Notional shares: 10B
        for $1T+ caps, 1B for $100B+, 500M for $10B+, else 100M."""
        if mc is None or mc <= 0:
            return None
        if mc > 1e12:
            shares = 1e10  # $100/share at $1T cap
        elif mc > 1e11:
            shares = 1e9
        elif mc > 1e10:
            shares = 5e8
        else:
            shares = 1e8
        return round(mc / shares, 2)

    revenue = _b(revenue_b)
    ebitda = (
        revenue * (ebitda_margin_pct / 100)
        if revenue is not None and ebitda_margin_pct is not None
        else None
    )
    net_income = (
        revenue * (net_margin_pct / 100)
        if revenue is not None and net_margin_pct is not None
        else None
    )
    ocf = _b(operating_cash_flow_b)
    capex = _b(capex_b)
    fcf = (ocf - capex) if (ocf is not None and capex is not None) else None
    gross_profit = (
        revenue * (gross_margin_pct / 100)
        if revenue is not None and gross_margin_pct is not None
        else None
    )

    return {
        "ticker": ticker,
        "companyName": name,
        "exchange": "NASDAQ" if ticker in {
            "AAPL", "MSFT", "NVDA", "GOOGL", "META", "AVGO", "ORCL", "CRM",
            "AMD", "INTC", "QCOM", "TXN", "MU", "ASML", "AMZN", "TSLA", "MDLZ",
            "ISRG", "NFLX", "CMCSA", "TMUS", "COST", "PEP", "BKNG", "SBUX",
        } else "NYSE",
        "sector": sector,
        "industry": None,
        "country": "USA",
        "currency": "USD",
        "mode": "demo",
        "price": _synth_price(_b(market_cap_b)),
        "marketCap": _b(market_cap_b),
        "enterpriseValue": (
            (_b(market_cap_b) + (_b(net_debt_b) or 0))
            if market_cap_b is not None
            else None
        ),
        "revenue": revenue,
        "revenueGrowth": revenue_growth_pct,
        "grossProfit": gross_profit,
        "grossMargin": gross_margin_pct,
        "ebitda": ebitda,
        "ebitdaMargin": ebitda_margin_pct,
        "operatingIncome": None,
        "netIncome": net_income,
        "netMargin": net_margin_pct,
        "cash": _b(cash_b),
        "grossDebt": _b(gross_debt_b),
        "netDebt": _b(net_debt_b),
        "equity": _b(equity_b),
        "operatingCashFlow": ocf,
        "capex": capex,
        "freeCashFlow": fcf,
        "peRatio": pe,
        "evToEbitda": ev_ebitda,
        "evToSales": ev_sales,
        "fcfYield": fcf_yield_pct,
        "dividendYield": dividend_yield_pct,
        "roe": roe_pct,
        "roa": roa_pct,
        "roic": None,
        "netDebtToEbitda": nd_to_ebitda,
        "debtToEquity": debt_to_equity,
        "currentRatio": None,
        "latestPeriod": "FY2024",
        "latestPeriodEnd": _LAST_UPDATED,
        "lastUpdated": _LAST_UPDATED,
        "source": "demo",
        "confidence": 0.6,
        "missingFields": [],
    }


