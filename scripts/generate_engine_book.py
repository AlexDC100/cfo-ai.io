def _iter_engine_modules() -> List[Path]:
    return sorted(p for p in SRC_ENGINE.rglob("*.py"))


def _module_name(path: Path) -> str:
    """src/engine/api/_reconcile.py -> engine.api._reconcile;
    src/engine/ir/__init__.py -> engine.ir."""
    rel = path.relative_to(SRC_ENGINE.parent)
    parts = list(rel.with_suffix("").parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _module_exists(dotted: str) -> bool:
    rel = Path(*dotted.split(".")[1:]) if dotted.startswith("engine") else None
    if dotted == "engine":
        return True
    if rel is None:
        return False
    return (SRC_ENGINE / rel).with_suffix(".py").exists() or (
        SRC_ENGINE / rel / "__init__.py"
    ).exists()


def _imports_of(path: Path) -> Tuple[Set[str], Set[str]]:
    """Return (engine_targets, external_toplevel_names) for one module."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    mod = _module_name(path)
    parts = mod.split(".")
    is_pkg = path.name == "__init__.py"
    engine_targets: Set[str] = set()
    external: Set[str] = set()

    def _add_engine(target: str, names: Optional[List[str]] = None) -> None:
        if not (target == "engine" or target.startswith("engine.")):
            return
        engine_targets.add(target)
        for n in names or []:
            cand = target + "." + n
            if _module_exists(cand):
                engine_targets.add(cand)

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name == "engine" or alias.name.startswith("engine."):
                    _add_engine(alias.name)
                else:
                    external.add(alias.name.split(".")[0])
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                base = parts if is_pkg else parts[:-1]
                strip = node.level - 1
                if strip:
                    base = base[: len(base) - strip]
                target = ".".join(base + (node.module.split(".") if node.module else []))
                _add_engine(target, [a.name for a in node.names])
            else:
                target = node.module or ""
                if target == "engine" or target.startswith("engine."):
                    _add_engine(target, [a.name for a in node.names])
                elif target:
                    external.add(target.split(".")[0])
    engine_targets.discard(mod)
    return engine_targets, external


def _package_of(dotted: str) -> str:
    """Grouping unit for the container view: first component under engine,
    if it is a real sub-package; root modules group as '(root)'."""
    parts = dotted.split(".")
    if len(parts) < 2:
        return "(root)"
    if (SRC_ENGINE / parts[1]).is_dir():
        return parts[1]
    return "(root)"


def build_import_graph() -> Dict[str, object]:
    modules = _iter_engine_modules()
    per_module: Dict[str, Set[str]] = {}
    per_module_external: Dict[str, Set[str]] = {}
    for p in modules:
        mod = _module_name(p)
        eng, ext = _imports_of(p)
        per_module[mod] = eng
        per_module_external[mod] = ext

    pkg_modules: Dict[str, Set[str]] = {}
    for mod in per_module:
        pkg_modules.setdefault(_package_of(mod), set()).add(mod)

    # Container edges: (importer_pkg, imported_pkg) -> number of importing modules
    edges: Dict[Tuple[str, str], Set[str]] = {}
    for mod, targets in per_module.items():
        src_pkg = _package_of(mod)
        for t in targets:
            dst_pkg = _package_of(t)
            if dst_pkg != src_pkg:
                edges.setdefault((src_pkg, dst_pkg), set()).add(mod)

    return {
        "per_module": per_module,
        "per_module_external": per_module_external,
        "pkg_modules": pkg_modules,
        "pkg_edges": {k: len(v) for k, v in edges.items()},
    }


def _declared_third_party() -> Dict[str, str]:
    """Import-name -> declared-dist-name map derived from pyproject.toml
    [project].dependencies (plus the import-name aliases)."""
    text = PYPROJECT.read_text(encoding="utf-8")
    m = re.search(r"^dependencies\s*=\s*\[(.*?)^\]", text, re.M | re.S)
    if not m:
        raise BookError("pyproject.toml: could not locate [project] dependencies")
    dists = re.findall(r'"([A-Za-z0-9_.-]+?)\s*[><=!~\[]', m.group(1))
    aliases = {"pyyaml": "yaml", "pymupdf": "fitz", "python-dateutil": "dateutil"}
    out: Dict[str, str] = {}
    for dist in dists:
        out[aliases.get(dist.lower(), dist.lower().replace("-", "_"))] = dist
    return out


