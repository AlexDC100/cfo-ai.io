def _assert_ids_in(module_path: str) -> List[str]:
    """A-ids actually present under a repo-relative module path (file or dir)."""
    root = REPO / module_path
    if not root.exists():
        raise BookError("money_path step names a missing module: %s" % module_path)
    files = [root] if root.is_file() else sorted(root.rglob("*.py"))
    ids: Set[str] = set()
    for f in files:
        for m in _ASSERT_ID.finditer(f.read_text(encoding="utf-8")):
            ids.add(m.group(0))
    return sorted(ids)


