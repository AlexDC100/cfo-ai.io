def _test_files() -> List[Path]:
    return sorted(p for p in TESTS_ENGINE.rglob("test_*.py"))


def _rel(p: Path) -> str:
    return p.relative_to(REPO).as_posix()


def discover_letter_invariants() -> Dict[str, List[str]]:
    """Bare-marker families in tests/engine: id -> sorted test files."""
    found: Dict[str, Set[str]] = {}
    for tf in _test_files():
        text = tf.read_text(encoding="utf-8")
        for m in _LETTER_MARKER.finditer(text):
            found.setdefault(m.group(0), set()).add(_rel(tf))
    return {k: sorted(v) for k, v in found.items()}


def discover_assert_ids() -> Dict[str, Dict[str, List[str]]]:
    """A-### ids: anchors in src/engine + witness test files in tests/engine."""
    src_anchor: Dict[str, Set[str]] = {}
    for p in _iter_engine_modules():
        text = p.read_text(encoding="utf-8")
        for m in _ASSERT_ID.finditer(text):
            src_anchor.setdefault(m.group(0), set()).add(_rel(p))
    witnesses: Dict[str, Set[str]] = {}
    for tf in _test_files():
        text = tf.read_text(encoding="utf-8")
        for m in _ASSERT_ID.finditer(text):
            if m.group(0) in src_anchor:
                witnesses.setdefault(m.group(0), set()).add(_rel(tf))
    return {
        aid: {"src": sorted(mods), "tests": sorted(witnesses.get(aid, set()))}
        for aid, mods in sorted(src_anchor.items())
    }


def discover_diag_codes() -> Dict[str, Dict[str, List[str]]]:
    """Full D*/R* code strings: defining src modules + resolving test files."""
    defined: Dict[str, Set[str]] = {}
    for p in _iter_engine_modules():
        text = p.read_text(encoding="utf-8")
        for m in _DIAG_CODE.finditer(text):
            defined.setdefault(m.group(1), set()).add(_rel(p))
    resolved: Dict[str, Set[str]] = {}
    for tf in _test_files():
        text = tf.read_text(encoding="utf-8")
        for code in defined:
            if code in text:
                resolved.setdefault(code, set()).add(_rel(tf))
    return {
        code: {"src": sorted(mods), "tests": sorted(resolved.get(code, set()))}
        for code, mods in sorted(defined.items())
    }


def build_catalog() -> Dict[str, Dict[str, object]]:
    """The full invariant catalog: id -> {family, meaning, tests, src}.

    Raises BookError when an id has no resolving test and is not a frozen
    KNOWN_GAPS entry — that is the generation-time half of K8's teeth.
    """
    catalog: Dict[str, Dict[str, object]] = {}

    for inv_id, files in discover_letter_invariants().items():
        catalog[inv_id] = {
            "family": inv_id[0],
            "meaning": CURATED_MEANING.get(
                inv_id,
                "(uncatalogued — add a curated meaning in scripts/generate_engine_book.py)",
            ),
            "tests": files,
            "src": [],
        }

    for aid, info in discover_assert_ids().items():
        catalog[aid] = {
            "family": "A",
            "meaning": "Always-on kernel assert — full contract + witness in assertions.md.",
            "tests": info["tests"],
            "src": info["src"],
        }

    for code, info in discover_diag_codes().items():
        catalog[code] = {
            "family": "D" if code.startswith("D") else "R",
            "meaning": CURATED_MEANING.get(
                code,
                "(uncatalogued — add a curated meaning in scripts/generate_engine_book.py)",
            ),
            "tests": info["tests"],
            "src": info["src"],
        }

    uncovered = sorted(k for k, v in catalog.items() if not v["tests"])
    unexpected = [k for k in uncovered if k not in KNOWN_GAPS]
    if unexpected:
        raise BookError(
            "invariants with NO resolving test (add a test or, consciously, "
            "a KNOWN_GAPS entry): %s" % ", ".join(unexpected)
        )
    stale = sorted(k for k in KNOWN_GAPS if k not in uncovered)
    if stale:
        raise BookError(
            "stale KNOWN_GAPS entries (now covered or no longer defined — "
            "remove them): %s" % ", ".join(stale)
        )
    return catalog


