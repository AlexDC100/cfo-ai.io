def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate in memory and byte-diff against the committed book",
    )
    args = parser.parse_args(argv)

    try:
        pages = generate()
    except BookError as exc:
        print("ENGINE BOOK GENERATION FAILED: %s" % exc, file=sys.stderr)
        return 1

    assert set(pages) == set(OWNED_PAGES)
    for foreign in FOREIGN_PAGES:
        assert foreign not in pages, "refusing to write agent-owned page %s" % foreign

    if args.check:
        drift: List[str] = []
        for name, content in sorted(pages.items()):
            target = BOOK_DIR / name
            if not target.exists():
                drift.append("%s: MISSING (never generated?)" % name)
            elif target.read_text(encoding="utf-8") != content:
                drift.append("%s: DRIFT (committed page != regeneration)" % name)
        if drift:
            print("ENGINE BOOK DRIFT — regenerate and commit:", file=sys.stderr)
            for d in drift:
                print("  " + d, file=sys.stderr)
            print("  fix: python scripts/generate_engine_book.py", file=sys.stderr)
            return 1
        print("engine book: clean (%d generated pages byte-identical)" % len(pages))
        return 0

    BOOK_DIR.mkdir(parents=True, exist_ok=True)
    for name, content in sorted(pages.items()):
        (BOOK_DIR / name).write_text(content, encoding="utf-8")
        print("wrote docs/engine_book/%s" % name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
