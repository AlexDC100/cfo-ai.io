def render_invariants(catalog: Dict[str, Dict[str, object]]) -> str:
    lines: List[str] = [GENERATED_HEADER]
    lines.append("# The invariant catalog\n")
    lines.append(
        "Every invariant family enforced on the engine, discovered from the\n"
        "tree (family markers in `tests/engine`, assert ids and diagnosis\n"
        "codes in `src/engine`) and linked to its enforcing tests. An\n"
        "invariant with no resolving test fails generation unless it is a\n"
        "frozen, visible entry in the known-gaps register below — that is\n"
        "the K8 gate's teeth (`tests/engine/test_engine_book.py`).\n"
        "\n"
        "The *enforced by* column lists every test file carrying the id's\n"
        "marker — the defining suite plus any suite that cross-references\n"
        "it (bare single-letter markers are file-level attributions).\n"
    )

    def _sort_key(inv_id: str) -> Tuple[str, int, str]:
        m = re.match(r"^([A-Z])-?(\d+)", inv_id)
        if m:
            return (m.group(1), int(m.group(2)), inv_id)
        return (inv_id[0], 999, inv_id)

    order = ["I", "P", "N", "M", "V", "K", "A", "D", "R"]
    for fam in order:
        ids = sorted((k for k, v in catalog.items() if v["family"] == fam), key=_sort_key)
        if not ids:
            continue
        lines.append("## %s-family — %s\n" % (fam, FAMILIES[fam]))
        if fam == "A":
            lines.append(
                "Per-assert contracts and witness anchors live in\n"
                "[assertions.md](assertions.md) (owned by the assertions agent).\n"
            )
        lines.append("| invariant | meaning | defined in | enforced by |")
        lines.append("|---|---|---|---|")
        for inv_id in ids:
            entry = catalog[inv_id]
            src = ", ".join("`%s`" % s for s in entry["src"]) or "—"
            tests = (
                ", ".join("`%s`" % t for t in entry["tests"])
                or "**NONE — known gap (see register below)**"
            )
            lines.append("| `%s` | %s | %s | %s |" % (inv_id, entry["meaning"], src, tests))
        lines.append("")

    lines.append("## Known-gaps register (drive to zero)\n")
    if KNOWN_GAPS:
        lines.append("| invariant | why it is still uncovered |")
        lines.append("|---|---|")
        for code in sorted(KNOWN_GAPS):
            lines.append("| `%s` | %s |" % (code, KNOWN_GAPS[code]))
    else:
        lines.append("(none — every catalogued invariant resolves to a test)")
    lines.append("")
    return "\n".join(lines)


def render_adr_index() -> str:
    lines: List[str] = [GENERATED_HEADER]
    lines.append("# ADR index — `docs/decisions/`\n")
    files = sorted(DECISIONS_DIR.glob("*.md"))
    if not files:
        raise BookError("docs/decisions/ has no ADRs — refusing to render an empty index")
    lines.append("| ADR | title |")
    lines.append("|---|---|")
    for f in files:
        title = ""
        for line in f.read_text(encoding="utf-8").splitlines():
            if line.startswith("#"):
                title = line.lstrip("#").strip()
                break
        lines.append("| [`%s`](../decisions/%s) | %s |" % (f.name, f.name, title or "(untitled)"))
    lines.append("")
    return "\n".join(lines)


